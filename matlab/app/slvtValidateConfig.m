function notes = slvtValidateConfig(cfg)
%SLVTVALIDATECONFIG Validate model inputs before any simulation starts.
    defaults = slvtDefaultConfig();
    required = fieldnames(defaults);
    for k = 1:numel(required)
        assert(isfield(cfg, required{k}), 'SLVT:Config', ...
            'Missing setting: %s.', required{k});
    end
    positive = {'totalMassLbm','payloadMassLbm','forwardMassLbm', ...
        'centralMassLbm','aftMassLbm','propellantMassLbm','bodyCd', ...
        'drogueCd','mainCd','payloadCd','bodyDiameterIn','finHeightIn', ...
        'finThicknessIn','finCount','railLengthFt','drogueDiameterFt', ...
        'mainDiameterFt','payloadDiameterFt','payloadDeployAltFt','g', ...
        'soundSpeedFtS','timeStepS','maxTimeS'};
    nonnegative = {'drogueHardwareLbm','mainHardwareLbm', ...
        'payloadHardwareLbm','drogueOpenS','mainOpenS','payloadOpenS'};
    for k = 1:numel(positive)
        x = cfg.(positive{k});
        assert(isnumeric(x) && isscalar(x) && isfinite(x) && x > 0, ...
            'SLVT:Config', '%s must be a finite positive number.', positive{k});
    end
    for k = 1:numel(nonnegative)
        x = cfg.(nonnegative{k});
        assert(isnumeric(x) && isscalar(x) && isfinite(x) && x >= 0, ...
            'SLVT:Config', '%s must be finite and nonnegative.', nonnegative{k});
    end
    assert(isnumeric(cfg.siteAltitudeFt) && isscalar(cfg.siteAltitudeFt) && isfinite(cfg.siteAltitudeFt) && ...
        cfg.siteAltitudeFt >= -1500 && cfg.siteAltitudeFt <= 65000, ...
        'SLVT:Config', 'Site altitude must be between -1500 and 65000 ft ASL.');
    assert(cfg.finCount == fix(cfg.finCount), 'SLVT:Config', 'Fin count must be an integer.');
    assert(cfg.timeStepS >= 0.0001 && cfg.timeStepS <= 0.02, ...
        'SLVT:Config', 'Time step must be between 0.0001 and 0.02 seconds.');
    assert(cfg.maxTimeS > cfg.timeStepS && cfg.maxTimeS <= 3600, ...
        'SLVT:Config', 'Maximum flight time must be greater than dt and at most 3600 s.');
    assert(cfg.maxTimeS / cfg.timeStepS <= 5000000, 'SLVT:Config', ...
        'Reduce maximum time or increase dt: at most 5 million steps per trajectory.');
    assert(islogical(cfg.useSectionTotal) && isscalar(cfg.useSectionTotal) && ...
        islogical(cfg.excludeHardwareMass) && isscalar(cfg.excludeHardwareMass), ...
        'SLVT:Config', 'Mass options must be logical scalars.');
    assert(isnumeric(cfg.drogueDelayS) && isvector(cfg.drogueDelayS) && ...
        numel(cfg.drogueDelayS) == 3 && all(isfinite(cfg.drogueDelayS)) && ...
        all(cfg.drogueDelayS >= 0), 'SLVT:Config', 'Enter three nonnegative drogue delays.');
    assert(isnumeric(cfg.mainDeployAltFt) && isvector(cfg.mainDeployAltFt) && ...
        numel(cfg.mainDeployAltFt) == 3 && all(isfinite(cfg.mainDeployAltFt)) && ...
        all(cfg.mainDeployAltFt > 0), 'SLVT:Config', 'Enter three positive main deployment altitudes.');
    assert(any(strcmp(cfg.motorThrustUnit, {'N','lbf'})), 'SLVT:Config', ...
        'Motor thrust units must be N or lbf.');
    assert(any(strcmp(cfg.atmosphere, {'standard','external'})), 'SLVT:Config', ...
        'Atmosphere must be standard or external.');
    assert(ischar(cfg.motorFile) || isstring(cfg.motorFile), 'SLVT:Config', ...
        'Motor file must be a path or filename.');
    assert(~isempty(char(cfg.motorFile)), 'SLVT:Config', 'Choose a motor CSV file.');
    if strcmp(cfg.atmosphere, 'external')
        assert(exist('atmos','file') == 2, 'SLVT:Config', ...
            'External atmosphere selected: put atmos.m on the MATLAB path.');
    end
    sectionSum = cfg.payloadMassLbm + cfg.forwardMassLbm + ...
        cfg.centralMassLbm + cfg.aftMassLbm;
    total = cfg.totalMassLbm;
    if cfg.useSectionTotal, total = sectionSum; end
    assert(total > cfg.propellantMassLbm + cfg.payloadMassLbm + ...
        cfg.drogueHardwareLbm + cfg.mainHardwareLbm, 'SLVT:Config', ...
        'Vehicle suspended mass would be zero or negative after deployment.');
    assert(cfg.aftMassLbm > cfg.propellantMassLbm + cfg.drogueHardwareLbm, ...
        'SLVT:Config', 'Aft mass must exceed propellant plus drogue hardware mass.');
    assert(cfg.centralMassLbm > cfg.mainHardwareLbm, 'SLVT:Config', ...
        'Central mass must exceed main recovery hardware mass.');
    assert(cfg.payloadMassLbm > cfg.payloadHardwareLbm, 'SLVT:Config', ...
        'Payload mass must exceed payload recovery hardware mass.');
    notes = {};
    if ~cfg.useSectionTotal && abs(total - sectionSum) > 1e-6
        notes{end+1} = sprintf(['Measured total is %.4f lbm; section sum is %.4f lbm. ' ...
            'Difference of %+.4f lbm is used in the vehicle dynamics but is not assigned to a section KE.'], ...
            total, sectionSum, total - sectionSum);
    end
    if cfg.timeStepS > 0.005
        notes{end+1} = 'dt exceeds 0.005 s: check convergence before using final results.';
    end
end
